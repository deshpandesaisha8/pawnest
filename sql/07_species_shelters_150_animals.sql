-- Block adding an animal when the shelter is full for that species, or does not take that species at all
CREATE TRIGGER trg_pets_capacity BEFORE INSERT ON pets FOR EACH ROW
BEGIN
  DECLARE cur INT;
  DECLARE cap INT;
  SELECT capacity INTO cap FROM shelter_capacity WHERE shelter_id = NEW.shelter_id AND species = NEW.species;
  IF cap IS NULL THEN
    SIGNAL SQLSTATE '45000' SET MESSAGE_TEXT = 'This shelter does not take this species';
  ELSE
    SELECT COUNT(*) INTO cur FROM pets WHERE shelter_id = NEW.shelter_id AND species = NEW.species AND status <> 'Adopted';
    IF cur >= cap THEN
      SIGNAL SQLSTATE '45000' SET MESSAGE_TEXT = 'Shelter is full for this species';
    END IF;
  END IF;
END$$
DELIMITER ;

DROP VIEW IF EXISTS v_capacity;
CREATE VIEW v_capacity AS
  SELECT s.shelter_id, s.name AS shelter, c.species, c.capacity,
         (SELECT COUNT(*) FROM pets p WHERE p.shelter_id = c.shelter_id AND p.species = c.species AND p.status <> 'Adopted') AS current_count
  FROM shelter_capacity c JOIN shelters s ON s.shelter_id = c.shelter_id;

