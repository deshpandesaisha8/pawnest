  shelter_id INT NOT NULL,
  species ENUM('Dog','Cat','Rabbit','Bird','Guinea Pig','Hamster','Turtle') NOT NULL,
  capacity INT NOT NULL,
  PRIMARY KEY (shelter_id, species),
